use file_source_common::FingerprintStrategy;
use proptest::prelude::*;

pub const NUM_SLOTS: usize = 4;

/// Simulation configuration explored by `proptest` alongside action traces.
#[derive(Debug, Clone)]
pub struct DstConfig {
    pub strategy: FingerprintStrategy,
    pub oldest_first: bool,
    pub max_read_bytes: usize,
    pub max_line_bytes: usize,
    pub max_bytes_per_read: Option<usize>,
    pub remove_after_secs: Option<u64>,
    pub rotate_wait_secs: u64,
}

impl Default for DstConfig {
    fn default() -> Self {
        Self {
            strategy: FingerprintStrategy::DevInode,
            oldest_first: false,
            max_read_bytes: 2048,
            max_line_bytes: 256,
            max_bytes_per_read: None,
            remove_after_secs: None,
            rotate_wait_secs: 300,
        }
    }
}

/// Strategy producing varied [`DstConfig`] combinations.
pub fn arb_dst_config() -> impl Strategy<Value = DstConfig> {
    let strategy = prop_oneof![
        Just(FingerprintStrategy::DevInode),
        Just(FingerprintStrategy::FirstLinesChecksum {
            ignored_header_bytes: 0,
            lines: 1,
        }),
        Just(FingerprintStrategy::FirstLinesChecksum {
            ignored_header_bytes: 0,
            lines: 2,
        }),
    ];
    let max_read_bytes = prop_oneof![Just(32usize), Just(256usize), Just(2048usize)];
    let max_bytes_per_read = prop_oneof![Just(None), Just(Some(1usize)), Just(Some(7usize))];

    (strategy, any::<bool>(), max_read_bytes, max_bytes_per_read).prop_map(
        |(strategy, oldest_first, max_read_bytes, max_bytes_per_read)| DstConfig {
            strategy,
            oldest_first,
            max_read_bytes,
            max_line_bytes: 128,
            max_bytes_per_read,
            remove_after_secs: None,
            rotate_wait_secs: 300,
        },
    )
}

/// A single discrete filesystem / writer / server action in a deterministic simulation trace.
///
/// Because this is a plain data structure generated by `proptest`, any failing
/// run is automatically shrunk to a minimal sequence of actions.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SimAction {
    /// Append a newline-terminated line to `slot` (creating the file if absent).
    AppendLine { slot: usize },
    /// Append an empty line (bare `\n`) to an existing file in `slot`.
    AppendEmptyLine { slot: usize },
    /// Append partial bytes without a trailing delimiter (sheared write).
    AppendPartial { slot: usize },
    /// Append a line exceeding `max_line_bytes` (must be discarded without
    /// corrupting subsequent lines).
    AppendOversizedLine { slot: usize },
    /// Append a line to a previously rotated file via its open inode fd
    /// (models a writer still flushing to the rotated file before SIGHUP).
    AppendToRotated { rotated_idx: usize },
    /// Create a 0-byte file in `slot` if empty (exercises `known_small_files`).
    CreateEmptyFile { slot: usize },
    /// Create a new gzip file (with 1 or 2 concatenated gzip members) in `slot`.
    CreateGzipFile { slot: usize, members: u8 },
    /// Rotate the file in `slot` inside the watched glob (rename + create fresh file).
    Rotate { slot: usize },
    /// Rotate the file in `slot` *outside* the watched glob (moves out of `include`,
    /// testing post-rename draining while unfindable).
    RotateOutsideGlob { slot: usize },
    /// Atomically retarget a symlink in `slot` to a fresh target file.
    SymlinkRotate { slot: usize },
    /// Unlink the file in `slot` (after ensuring discovery).
    Unlink { slot: usize },
    /// Toggle read permissions (`EACCES` fault injection & recovery) on `slot`.
    ToggleReadable { slot: usize },
    /// Advance `SimClock` by `advance_ms` milliseconds and execute one `FileServerState::step`.
    Step { advance_ms: u64 },
    /// Advance `SimClock` without polling (exercises idle backoff, glob cooldown, checkpoint expiry).
    AdvanceClock { advance_secs: u64 },
    /// Acknowledge all currently buffered (unacked) lines into `CheckpointsView`.
    AckPending,
    /// Persist checkpoints to disk, optionally injecting a partial-write crash
    /// (`Some(n)` writes only the first `n` bytes to `checkpoints.new.json` and fails).
    CheckpointFlush { crash_bytes: Option<usize> },
    /// Drop `FileServerState` and restart from persisted checkpoints on disk.
    Restart,
}

/// Strategy producing weighted [`SimAction`] values that shrink cleanly.
pub fn arb_action() -> impl Strategy<Value = SimAction> {
    let slot = 0..NUM_SLOTS;
    prop_oneof![
        30 => slot.clone().prop_map(|slot| SimAction::AppendLine { slot }),
        5  => slot.clone().prop_map(|slot| SimAction::AppendEmptyLine { slot }),
        10 => slot.clone().prop_map(|slot| SimAction::AppendPartial { slot }),
        5  => slot.clone().prop_map(|slot| SimAction::AppendOversizedLine { slot }),
        5  => (0usize..4).prop_map(|rotated_idx| SimAction::AppendToRotated { rotated_idx }),
        3  => slot.clone().prop_map(|slot| SimAction::CreateEmptyFile { slot }),
        3  => (slot.clone(), 1u8..=2).prop_map(|(slot, members)| SimAction::CreateGzipFile { slot, members }),
        8  => slot.clone().prop_map(|slot| SimAction::Rotate { slot }),
        4  => slot.clone().prop_map(|slot| SimAction::RotateOutsideGlob { slot }),
        4  => slot.clone().prop_map(|slot| SimAction::SymlinkRotate { slot }),
        5  => slot.clone().prop_map(|slot| SimAction::Unlink { slot }),
        4  => slot.prop_map(|slot| SimAction::ToggleReadable { slot }),
        14 => (50u64..1600u64).prop_map(|advance_ms| SimAction::Step { advance_ms }),
        4  => (1u64..15u64).prop_map(|advance_secs| SimAction::AdvanceClock { advance_secs }),
        6  => Just(SimAction::AckPending),
        5  => prop_oneof![
            3 => Just(SimAction::CheckpointFlush { crash_bytes: None }),
            1 => (0usize..32).prop_map(|n| SimAction::CheckpointFlush { crash_bytes: Some(n) }),
        ],
        5  => Just(SimAction::Restart),
    ]
}

/// Strategy producing a sequence of up to `max_len` [`SimAction`]s.
pub fn arb_actions(max_len: usize) -> impl Strategy<Value = Vec<SimAction>> {
    prop::collection::vec(arb_action(), 1..=max_len)
}
